namespace DraftEngine.Analysis;

/// <summary>Kind of file an analysis was built from.</summary>
public enum DocumentFormat
{
    Docx,
    Pdf,
    PlainText
}

/// <summary>A paragraph with a stable id and character offsets into <see cref="NormalizedDocument.Text"/>.</summary>
public sealed record DocumentParagraph(
    string Id,
    int Index,
    string Text,
    int StartOffset,
    int EndOffset,
    bool IsHeading);

/// <summary>
/// Imported document in a single normalized form. Offsets are UTF-16 character offsets into
/// <see cref="Text"/>, so a finding quote can be located in the viewer without re-parsing.
/// </summary>
public sealed class NormalizedDocument
{
    public required string FileName { get; init; }
    public required DocumentFormat Format { get; init; }
    public required string Text { get; init; }
    public required IReadOnlyList<DocumentParagraph> Paragraphs { get; init; }
    public bool HasTextLayer { get; init; } = true;

    /// <summary>Extracts the text slice for a character range, clamped to the document.</summary>
    public string Slice(int startOffset, int length)
    {
        if (startOffset < 0 || length <= 0 || startOffset >= Text.Length)
        {
            return string.Empty;
        }

        return Text.Substring(startOffset, Math.Min(length, Text.Length - startOffset));
    }
}

/// <summary>A segmented contract clause with its heading, category and source range.</summary>
public sealed class AnalyzedClause
{
    public required string Id { get; init; }
    public required int Number { get; init; }
    public required string Heading { get; init; }
    public required string Category { get; init; }
    public required string Text { get; init; }
    public required int StartOffset { get; init; }
    public required int EndOffset { get; init; }
}

public enum FindingSeverity
{
    Info = 0,
    Low = 1,
    Medium = 2,
    High = 3,
    Critical = 4
}

/// <summary>
/// One review finding. <see cref="Quote"/> always exists verbatim in the source document
/// (whitespace-normalized), which is what makes an AI finding trustworthy.
/// </summary>
public sealed class AnalysisFinding
{
    public required string Id { get; init; }
    public required string RuleId { get; init; }
    public required FindingSeverity Severity { get; init; }
    public required string Category { get; init; }
    public required string Title { get; init; }
    public required string Quote { get; init; }
    public required string Explanation { get; init; }
    public string SuggestedFix { get; init; } = string.Empty;
    public string? ClauseId { get; init; }
    public int StartOffset { get; init; }
    public bool IsAiGenerated { get; init; }
}

/// <summary>A value extracted deterministically from the document (never generated by AI).</summary>
public sealed record ExtractedFact(string Name, string? Value, string Quote, bool Found);

public enum PlaybookRuleKind
{
    /// <summary>A clause category that should be present.</summary>
    RequiredClause,

    /// <summary>A regex that indicates a one-sided or risky term.</summary>
    RedFlag,

    /// <summary>A fact that should be stated (for example governing law).</summary>
    RequiredFact
}

/// <summary>A configurable playbook rule. Users can edit required clauses and red flags.</summary>
public sealed class PlaybookRule
{
    public required string Id { get; init; }
    public required PlaybookRuleKind Kind { get; init; }
    public required string Category { get; init; }
    public required string Description { get; init; }
    public required FindingSeverity Severity { get; init; }

    /// <summary>Case-insensitive keywords that identify the clause category.</summary>
    public IReadOnlyList<string> Keywords { get; init; } = [];

    /// <summary>Regex used by <see cref="PlaybookRuleKind.RedFlag"/> rules.</summary>
    public string? Pattern { get; init; }

    /// <summary>Library category suggested when inserting a missing clause.</summary>
    public string? SuggestedClauseCategory { get; init; }
}

/// <summary>A per-contract-type review playbook.</summary>
public sealed class Playbook
{
    public required string ContractType { get; init; }
    public required string DisplayName { get; init; }
    public List<PlaybookRule> Rules { get; init; } = [];
}

/// <summary>Options controlling a single analysis run.</summary>
public sealed class AnalysisOptions
{
    /// <summary>Canonical contract type used to choose a built-in playbook.</summary>
    public string? ContractType { get; init; }

    /// <summary>AI review is opt-in and requires consent; deterministic checks always run.</summary>
    public bool UseAi { get; init; }

    /// <summary>Must be true for <see cref="UseAi"/> to have any effect.</summary>
    public bool AiConsentGranted { get; init; }

    public Playbook? PlaybookOverride { get; init; }
}

/// <summary>Counters that explain what happened during a run.</summary>
public sealed class AnalysisStatistics
{
    public int ParagraphCount { get; init; }
    public int ClauseCount { get; init; }
    public int FindingsCount { get; init; }
    public bool AiUsed { get; init; }
    public int AiFindingsAccepted { get; init; }
    public int AiFindingsDiscarded { get; init; }
    public string? AiError { get; init; }
    public long DurationMilliseconds { get; init; }
}

/// <summary>The complete, persistable result of one analysis.</summary>
public sealed class AnalysisResult
{
    public required NormalizedDocument Document { get; init; }
    public required IReadOnlyList<AnalyzedClause> Clauses { get; init; }
    public required IReadOnlyList<AnalysisFinding> Findings { get; init; }
    public required IReadOnlyList<ExtractedFact> Facts { get; init; }
    public required AnalysisStatistics Statistics { get; init; }
    public required Playbook Playbook { get; init; }

    /// <summary>Mandatory disclaimer shown wherever findings are displayed or exported.</summary>
    public static string Disclaimer => "Not legal advice. Review by a licensed attorney required.";
}

/// <summary>Thrown when a file cannot be imported (unsupported type, corrupt file, no text layer).</summary>
public sealed class DocumentImportException : Exception
{
    public DocumentImportException(string message, Exception? inner = null) : base(message, inner)
    {
    }
}
